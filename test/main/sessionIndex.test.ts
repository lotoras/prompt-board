import { afterEach, beforeEach, describe, expect, it } from 'vitest'
import { promises as fs } from 'fs'
import os from 'os'
import { join } from 'path'
import { listProjectSessions, summarizeTranscript } from '../../src/main/chat/sessionIndex'

const J = (o: unknown): string => JSON.stringify(o)
const lines = (...rows: unknown[]): string => rows.map(J).join('\n') + '\n'

const userRec = (content: unknown, extra: Record<string, unknown> = {}) => ({
  type: 'user',
  uuid: 'u-' + Math.random().toString(36).slice(2),
  message: { role: 'user', content },
  ...extra
})
const assistantRec = (model: string) => ({
  type: 'assistant',
  uuid: 'a-' + Math.random().toString(36).slice(2),
  message: { id: 'm', role: 'assistant', model, content: [{ type: 'text', text: 'ok' }] }
})

describe('chat/sessionIndex summarizeTranscript', () => {
  it('takes cwd from the first record that has one', () => {
    const head = lines(
      { type: 'summary' },
      userRec('hi', { cwd: 'C:\\work\\p1' }),
      userRec('again', { cwd: 'C:\\other' })
    )
    expect(summarizeTranscript(head, '').cwd).toBe('C:\\work\\p1')
  })

  it('skips meta, command, caveat and system-reminder lines for the first prompt', () => {
    const head = lines(
      userRec('Caveat: injected', { isMeta: true, cwd: 'C:\\work\\p1' }),
      userRec('<local-command-caveat>Caveat: generated by the user</local-command-caveat>'),
      userRec('<local-command-stdout>ok</local-command-stdout>'),
      userRec('<command-name>/cost</command-name>\n<command-args></command-args>'),
      userRec('<system-reminder>be nice</system-reminder>'),
      userRec('fix the login bug')
    )
    expect(summarizeTranscript(head, '').firstPrompt).toBe('fix the login bug')
  })

  it('reads text blocks of array content', () => {
    const head = lines(
      userRec([{ type: 'text', text: 'from a block' }], { cwd: 'C:\\work\\p1' })
    )
    expect(summarizeTranscript(head, '').firstPrompt).toBe('from a block')
  })

  it('strips the directive trailer and keeps only the first line', () => {
    const head = lines(userRec('fix it\nsecond line\n\nultrathink\nuse codex'))
    expect(summarizeTranscript(head, '').firstPrompt).toBe('fix it')
  })

  it('caps the first prompt at 120 characters', () => {
    const head = lines(userRec('x'.repeat(300)))
    expect(summarizeTranscript(head, '').firstPrompt).toHaveLength(120)
  })

  it('returns an empty firstPrompt when there is none', () => {
    expect(summarizeTranscript(lines({ type: 'summary' }), '').firstPrompt).toBe('')
  })

  it('uses the last aiTitle from the tail, else the head, else the first prompt', () => {
    const head = lines(userRec('first prompt'), { type: 'ai-title', aiTitle: 'Head title' })
    const tail = lines(
      { type: 'ai-title', aiTitle: 'Old tail title' },
      { type: 'ai-title', aiTitle: 'Newest tail title' }
    )
    expect(summarizeTranscript(head, tail).title).toBe('Newest tail title')
    expect(summarizeTranscript(head, '').title).toBe('Head title')
    expect(summarizeTranscript(lines(userRec('first prompt')), '').title).toBe('first prompt')
  })

  it('takes the last message.model from the tail, else the head', () => {
    const head = lines(userRec('hi'), assistantRec('claude-opus-5-5'))
    const tail = lines(assistantRec('claude-sonnet-5-5'), assistantRec('claude-fable-5-1'))
    expect(summarizeTranscript(head, tail).model).toBe('claude-fable-5-1')
    expect(summarizeTranscript(head, '').model).toBe('claude-opus-5-5')
    expect(summarizeTranscript(lines(userRec('hi')), '').model).toBeUndefined()
  })

  it('tolerates a partial (cut) first/last line', () => {
    const head = lines(userRec('hello there', { cwd: 'C:\\work\\p1' })) + '{"type":"assis'
    const tail = '{"type":"user","mess\n' + lines({ type: 'ai-title', aiTitle: 'T' })
    const s = summarizeTranscript(head, tail)
    expect(s.firstPrompt).toBe('hello there')
    expect(s.title).toBe('T')
  })
})

describe('chat/sessionIndex listProjectSessions', () => {
  let dir: string
  const PROJECT = 'c:/work/p1'
  const CWD = 'C:\\work\\p1'
  const WT_CWD = 'C:\\work\\p1\\.claude\\worktrees\\feat-x'

  beforeEach(async () => {
    dir = await fs.mkdtemp(join(os.tmpdir(), 'session-index-'))
  })
  afterEach(async () => {
    await fs.rm(dir, { recursive: true, force: true })
  })

  async function write(
    sub: string,
    name: string,
    content: string,
    mtimeSec: number
  ): Promise<void> {
    await fs.mkdir(join(dir, sub), { recursive: true })
    const p = join(dir, sub, name)
    await fs.writeFile(p, content)
    await fs.utimes(p, mtimeSec, mtimeSec)
  }

  const session = (cwd: string, prompt: string, extra: unknown[] = []): string =>
    lines(userRec(prompt, { cwd }), assistantRec('claude-opus-5-5'), ...extra)

  it('lists this project newest first, with worktree sessions and metadata', async () => {
    await write('enc-a', 'old.jsonl', session(CWD, 'old prompt'), 1_000)
    await write(
      'enc-a',
      'new.jsonl',
      session(CWD, 'new prompt', [{ type: 'ai-title', aiTitle: 'Nice title' }]),
      3_000
    )
    await write('enc-wt', 'wt.jsonl', session(WT_CWD, 'worktree prompt'), 2_000)

    const out = await listProjectSessions(PROJECT, { projectsDir: dir })
    expect(out.map((s) => s.sessionId)).toEqual(['new', 'wt', 'old'])
    expect(out[0]).toMatchObject({
      sessionId: 'new',
      title: 'Nice title',
      firstPrompt: 'new prompt',
      cwd: CWD,
      model: 'claude-opus-5-5',
      lastActivity: 3_000_000
    })
    expect(out[0].worktreeRel).toBeUndefined()
    expect(out[1]).toMatchObject({
      sessionId: 'wt',
      cwd: WT_CWD,
      worktreeRel: '.claude/worktrees/feat-x',
      title: 'worktree prompt'
    })
  })

  it('filters out other projects, including lookalike prefixes', async () => {
    await write('enc-a', 'mine.jsonl', session(CWD, 'mine'), 1_000)
    await write('enc-b', 'other.jsonl', session('C:\\work\\p2', 'other'), 2_000)
    await write('enc-c', 'prefix.jsonl', session('C:\\work\\p1-extra', 'lookalike'), 3_000)
    await write('enc-d', 'nested.jsonl', session('C:\\work\\p1\\src', 'subdir'), 4_000)

    const out = await listProjectSessions(PROJECT, { projectsDir: dir })
    expect(out.map((s) => s.sessionId)).toEqual(['mine'])
  })

  it('skips agent-*.jsonl, non-jsonl files and files without a prompt', async () => {
    await write('enc-a', 'agent-abc.jsonl', session(CWD, 'sub agent'), 5_000)
    await write('enc-a', 'notes.txt', 'x', 5_000)
    await write(
      'enc-a',
      'empty.jsonl',
      lines({ type: 'summary', cwd: CWD }, userRec('<system-reminder>x</system-reminder>', { cwd: CWD })),
      5_000
    )
    await write('enc-a', 'real.jsonl', session(CWD, 'real'), 1_000)

    const out = await listProjectSessions(PROJECT, { projectsDir: dir })
    expect(out.map((s) => s.sessionId)).toEqual(['real'])
  })

  it('honours limit', async () => {
    for (let i = 1; i <= 5; i++) {
      await write('enc-a', `s${i}.jsonl`, session(CWD, 'p' + i), i * 1000)
    }
    const out = await listProjectSessions(PROJECT, { projectsDir: dir, limit: 2 })
    expect(out.map((s) => s.sessionId)).toEqual(['s5', 's4'])
  })

  it('returns [] for a missing projects dir', async () => {
    expect(await listProjectSessions(PROJECT, { projectsDir: join(dir, 'nope') })).toEqual([])
  })

  it('reflects a changed transcript (cache keyed by mtime and size)', async () => {
    await write('enc-a', 's.jsonl', session(CWD, 'before'), 1_000)
    expect((await listProjectSessions(PROJECT, { projectsDir: dir }))[0].title).toBe('before')
    await write(
      'enc-a',
      's.jsonl',
      session(CWD, 'before', [{ type: 'ai-title', aiTitle: 'After' }]),
      2_000
    )
    expect((await listProjectSessions(PROJECT, { projectsDir: dir }))[0].title).toBe('After')
  })
})
